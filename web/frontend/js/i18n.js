  function dyn(s) {
    if (typeof s !== "string" || !s || getLang() === "kk") return s;
    if (Object.prototype.hasOwnProperty.call(RU, s)) return RU[s];
    for (var i = 0; i < RULES.length; i++) {
      var m = s.match(RULES[i][0]);
      if (m) return RULES[i][1](m);
    }
    return s;
  }

  function tr(key, vars) {
    var pair = K[key];
    var s = pair ? pair[getLang() === "ru" ? 1 : 0] : key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (_, n) { return vars[n] != null ? vars[n] : ""; });
    return s;
  }

