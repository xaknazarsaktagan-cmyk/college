    root.querySelectorAll("[data-i18n-ph]").forEach(function (e) { e.setAttribute("placeholder", tr(e.getAttribute("data-i18n-ph"))); });
    root.querySelectorAll("[data-i18n-aria]").forEach(function (e) { e.setAttribute("aria-label", tr(e.getAttribute("data-i18n-aria"))); });
    var ti = document.querySelector("title[data-i18n]");
