      host.querySelectorAll(".titem").forEach(function (b) { b.setAttribute("aria-checked", String(b.getAttribute("data-t") === th)); });
      host.querySelectorAll("button[data-m]").forEach(function (b) { b.setAttribute("aria-pressed", String((b.getAttribute("data-m") === "night") === isDark(th))); });
