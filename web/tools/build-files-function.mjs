import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../supabase/functions/document-files/',import.meta.url);
const handler=await readFile(new URL('handler.ts',base),'utf8');
const verifier=await readFile(new URL('firebase-jwt.ts',base),'utf8');
const entry=await readFile(new URL('index.ts',base),'utf8');
const source='// Generated by npm run build:files-function. Source: supabase/functions/document-files/.\n'+
  handler.replace(/export /g,'')+'\n'+verifier.replace(/export /g,'')+'\n'+
  entry.split('\n').filter(line=>!line.includes("from './handler.ts'")&&!line.includes("from './firebase-jwt.ts'")).join('\n');
await writeFile(new URL('../supabase/document-files-dashboard.ts',import.meta.url),source);
console.log('Created supabase/document-files-dashboard.ts');
